<#
.SYNOPSIS
    Configure real Google Sign-In for DAV once you have an OAuth 2.0 Client ID.

.DESCRIPTION
    Takes a Google OAuth 2.0 Client ID ("Web application" type) and wires it into
    both sides of the app:

      frontend/.env   VITE_GOOGLE_CLIENT_ID  -> baked into the bundle at build time
      backend/.env    GOOGLE_CLIENT_ID       -> verifies the ID token audience

    Both MUST be the same value, or the backend rejects the token with
    "Token audience does not match configured Google Client ID".

    Then rebuilds and verifies.

.PARAMETER ClientId
    The client ID, e.g. 123456789-abc.apps.googleusercontent.com

.EXAMPLE
    ./configure-google-oauth.ps1 -ClientId 123456789-abc.apps.googleusercontent.com
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    # Single-quoted so the backslashes stay literal. A PowerShell 6+ r'' raw
    # string would be a parse error on Windows PowerShell 5.1.
    [ValidatePattern('^\d+-[a-z0-9]+\.apps\.googleusercontent\.com$')]
    [string]$ClientId,

    [switch]$NoDocker,
    [switch]$SkipVerify
)

$ErrorActionPreference = "Stop"
$Root = $PSScriptRoot

function Write-Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Write-Ok($msg)   { Write-Host "    OK  $msg" -ForegroundColor Green }

Write-Host "=============================================" -ForegroundColor Yellow
Write-Host "  DAV - Google Sign-In Configuration" -ForegroundColor Yellow
Write-Host "=============================================" -ForegroundColor Yellow

# ---------------------------------------------------------------- frontend
Write-Step "Writing frontend/.env"
$frontEnv = Join-Path $Root "frontend\.env"
@(
    "# Generated by configure-google-oauth.ps1",
    "# Relative API path: the app calls whichever origin served it. An absolute",
    "# host would break on a phone (localhost would mean the phone itself).",
    "VITE_API_BASE_URL=/api/v1",
    "",
    "# Public OAuth client ID from Google Cloud Console.",
    "# Safe to expose in a browser bundle; it is a public identifier.",
    "VITE_GOOGLE_CLIENT_ID=$ClientId"
) | Set-Content -LiteralPath $frontEnv -Encoding UTF8
Write-Ok $frontEnv

# ----------------------------------------------------------------- backend
Write-Step "Writing backend/.env"
$backEnv = Join-Path $Root "backend\.env"
$backLines = @(
    "# Generated by configure-google-oauth.ps1",
    "ENVIRONMENT=development",
    "DEBUG=True",
    "HOST=0.0.0.0",
    "PORT=8000",
    "CORS_ORIGINS=*",
    "",
    "# Public client ID. Used to verify the `aud` claim of an incoming ID token.",
    "# Must match VITE_GOOGLE_CLIENT_ID exactly.",
    "GOOGLE_CLIENT_ID=$ClientId",
    "",
    "DEV_MOCK_OTP=44444",
    "OTP_PROVIDER=mock"
)
# Preserve an existing DATABASE_URL if the developer already set one.
if (Test-Path -LiteralPath $backEnv) {
    $existing = Get-Content -LiteralPath $backEnv -ErrorAction SilentlyContinue
    if ($existing -and ($existing -match '^\s*DATABASE_URL=')) {
        $backLines += ""
        $backLines += ($existing | Where-Object { $_ -match '^\s*DATABASE_URL=' })
        Write-Ok "preserved existing DATABASE_URL"
    }
}
$backLines | Set-Content -LiteralPath $backEnv -Encoding UTF8
Write-Ok $backEnv

# ----------------------------------------------------------------- root env
# Compose resolves ${VITE_GOOGLE_CLIENT_ID} from the shell or from a .env file
# sitting NEXT TO docker-compose.yml. It does NOT read backend/.env or
# frontend/.env, and both are excluded from the Docker build context. Without
# this file the build arg and the backend container env both stay empty and the
# app silently keeps using the demo sign-in.
Write-Step "Writing root .env (read by docker compose)"
$rootEnv = Join-Path $Root ".env"
@(
    "# Generated by configure-google-oauth.ps1",
    "# Read by docker compose for the frontend build arg and the backend env.",
    "VITE_GOOGLE_CLIENT_ID=$ClientId"
) | Set-Content -LiteralPath $rootEnv -Encoding UTF8
Write-Ok $rootEnv

# ------------------------------------------------------------------- docker
if (-not $NoDocker) {
    Write-Step "Rebuilding containers"
    Push-Location $Root
    try {
        # Vite inlines VITE_* at build time, so the image MUST be rebuilt -
        # restarting alone would keep serving the old bundle without the ID.
        docker compose --profile tls up --build -d
        if ($LASTEXITCODE -ne 0) { throw "docker compose failed with exit code $LASTEXITCODE" }
        Write-Ok "containers rebuilt"
    } finally {
        Pop-Location
    }
}

# ------------------------------------------------------------------- verify
if (-not $SkipVerify) {
    Write-Step "Verifying the backend can now verify real tokens"
    try {
        $health = Invoke-WebRequest -Uri "http://127.0.0.1:8001/health" -UseBasicParsing -TimeoutSec 20
        Write-Ok "backend healthy ($($health.StatusCode))"
    } catch {
        Write-Host "    WARN backend not reachable on :8001 - $($_.Exception.Message)" -ForegroundColor Yellow
    }

    $logs = docker compose -f (Join-Path $Root "docker-compose.yml") logs backend --tail 40 2>&1 | Out-String
    if ($logs -match "GOOGLE OAuth:\s+Google OAuth \[Configured") {
        Write-Ok "startup log confirms Google OAuth is configured"
    } else {
        Write-Host "    NOTE startup log still shows Google OAuth unconfigured." -ForegroundColor Yellow
        Write-Host "         Check backend/.env and rebuild: docker compose --profile tls up --build -d" -ForegroundColor Yellow
    }
}

Write-Host "`n=============================================" -ForegroundColor Green
Write-Host "  Google Sign-In configured" -ForegroundColor Green
Write-Host "=============================================" -ForegroundColor Green
Write-Host ""
Write-Host "Test it:" -ForegroundColor White
Write-Host "  1. Open https://<your-LAN-IP>:8443 (accept the cert warning)" -ForegroundColor Gray
Write-Host "  2. Tap 'Continue with Google' - Google's real button appears" -ForegroundColor Gray
Write-Host "  3. Sign in with a real Google account" -ForegroundColor Gray
Write-Host ""
Write-Host "Add these origins in the Cloud Console under 'Authorized JavaScript origins':" -ForegroundColor Yellow
Write-Host "  https://localhost:8443" -ForegroundColor Gray
Write-Host "  https://<your-LAN-IP>:8443" -ForegroundColor Gray
Write-Host "  http://localhost:8080" -ForegroundColor Gray
Write-Host ""
